r = {}
for i in range(len(lines)):
    line = lines[i]
    if line == "" or line == "\n" or line == " ":
        assert len(r['trials']) == r['attempts']
        runs.append(r)
        r = {}
        continue
    # first expected line STATISTICS_ATTEMPTS
    if 'STATISTICS_ATTEMPTS' in line:
        r['attempts'] = int(line.split(': ')[1])
        r['trials'] = []
    if 'Accuracy on labeled' in line:
        r['trials'].append(float(line.split(': ')[1].split(' ')[0]))

